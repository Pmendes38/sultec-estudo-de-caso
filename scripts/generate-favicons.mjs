/**
 * Generate favicon set from public/sultec/logo/logo.png
 * Outputs:
 *   - public/favicon.ico            (multi-size: 16, 32, 48)
 *   - public/icon.png                (32×32 — Next.js app router auto-favicon)
 *   - public/apple-icon.png          (180×180 — Next.js app router auto-apple-touch)
 *   - public/favicon-16x16.png
 *   - public/favicon-32x32.png
 *   - public/android-chrome-192x192.png
 *   - public/android-chrome-512x512.png
 *   - public/site.webmanifest
 *   - PASTA CRIAÇÃO SITE SULTEC/sultec_favicons/  (full copy)
 */

import sharp from 'sharp'
import fs from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()
const src = path.join(root, 'public', 'sultec', 'logo', 'logo.png')
const publicDir = path.join(root, 'public')
const figmaDir = path.join(root, 'PASTA CRIAÇÃO SITE SULTEC', 'sultec_favicons')

const BG = { r: 7, g: 8, b: 8, alpha: 1 } // #070808 — Sultec dark background

const sizes = [
  { size: 16, name: 'favicon-16x16.png' },
  { size: 32, name: 'favicon-32x32.png' },
  { size: 32, name: 'icon.png' }, // Next.js auto-favicon
  { size: 180, name: 'apple-icon.png', padded: true },
  { size: 180, name: 'apple-touch-icon.png', padded: true },
  { size: 192, name: 'android-chrome-192x192.png', padded: true },
  { size: 512, name: 'android-chrome-512x512.png', padded: true },
]

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true })
}

async function generatePng({ size, padded }) {
  // Logo gets a small padding so it doesn't touch the edges (10% of size)
  const pad = padded ? Math.round(size * 0.12) : 0
  const inner = size - pad * 2

  const logoBuffer = await sharp(src)
    .resize(inner, inner, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .toBuffer()

  return sharp({
    create: {
      width: size,
      height: size,
      channels: 4,
      background: padded ? BG : { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite([{ input: logoBuffer, top: pad, left: pad }])
    .png()
    .toBuffer()
}

async function generateIco() {
  // ICO is generated by stacking the smallest PNGs. sharp doesn't write .ico
  // natively, so we just write a 32×32 PNG renamed (modern browsers accept it).
  const png = await generatePng({ size: 32, padded: false })
  return png
}

async function writeWebmanifest(dir) {
  const manifest = {
    name: 'Sultec — Soluções Tecnológicas',
    short_name: 'Sultec',
    description: 'Tecnologia, estrutura e excelência operacional.',
    icons: [
      { src: '/android-chrome-192x192.png', sizes: '192x192', type: 'image/png' },
      { src: '/android-chrome-512x512.png', sizes: '512x512', type: 'image/png' },
    ],
    theme_color: '#F35901',
    background_color: '#070808',
    display: 'standalone',
    start_url: '/',
  }
  await fs.writeFile(path.join(dir, 'site.webmanifest'), JSON.stringify(manifest, null, 2))
}

async function main() {
  await ensureDir(publicDir)
  await ensureDir(figmaDir)

  for (const item of sizes) {
    const buf = await generatePng(item)
    await fs.writeFile(path.join(publicDir, item.name), buf)
    await fs.writeFile(path.join(figmaDir, item.name), buf)
    console.log(`  ✓ ${item.name} (${item.size}×${item.size})`)
  }

  const ico = await generateIco()
  await fs.writeFile(path.join(publicDir, 'favicon.ico'), ico)
  await fs.writeFile(path.join(figmaDir, 'favicon.ico'), ico)
  console.log('  ✓ favicon.ico')

  await writeWebmanifest(publicDir)
  await writeWebmanifest(figmaDir)
  console.log('  ✓ site.webmanifest')

  console.log('\nDone.')
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
